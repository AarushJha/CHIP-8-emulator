import sys 

FONTSET = [
    0xF0, 0x90, 0x90, 0x90, 0xF0,  # 0
    0x20, 0x60, 0x20, 0x20, 0x70,  # 1
    0xF0, 0x10, 0xF0, 0x80, 0xF0,  # 2
    0xF0, 0x10, 0xF0, 0x10, 0xF0,  # 3
    0x90, 0x90, 0xF0, 0x10, 0x10,  # 4
    0xF0, 0x80, 0xF0, 0x10, 0xF0,  # 5
    0xF0, 0x80, 0xF0, 0x90, 0xF0,  # 6
    0xF0, 0x10, 0x20, 0x40, 0x40,  # 7
    0xF0, 0x90, 0xF0, 0x90, 0xF0,  # 8
    0xF0, 0x90, 0xF0, 0x10, 0xF0,  # 9
    0xF0, 0x90, 0xF0, 0x90, 0x90,  # A
    0xE0, 0x90, 0xE0, 0x90, 0xE0,  # B
    0xF0, 0x80, 0x80, 0x80, 0xF0,  # C
    0xE0, 0x90, 0x90, 0x90, 0xE0,  # D
    0xF0, 0x80, 0xF0, 0x80, 0xF0,  # E
    0xF0, 0x80, 0xF0, 0x80, 0x80   # F
]

class CPU:
    def __init__(self, display, keypad):
        self.memory = bytearray(4096)
        self.v = bytearray(16)
        self.i = 0
        self.pc = 0x200
        self.stack = [0] * 16
        self.sp = 0

        self.delay_timer = 0
        self.sound_timer = 0

        self.display = display
        self.keypad = keypad

        # Load fontset into memory at 0x50
        self.memory[0x50:0x50 + len(FONTSET)] = FONTSET

    def load_room(self, filename):
        with open(filename, "rb") as f:
            rom_data = f.read()
            self.memory[0x200:0x200 + len(rom_data)] = rom_data

    def emulate_cycle(self):
        # Fetch 2-byte opcode
        opcode = (self.memory[self.pc] << 8) | self.memory[self.pc + 1]
        self.pc += 2

        # --- DECODE AND EXECUTE OPCODES GO HERE ---
        # Example: 0x00E0 clears the screen
        if opcode == 0x00E0:
            self.display.clear()
